"""Generate game/invocations_2024.go from the SRD Eldritch Invocation Options (cmd/server/data/srd521_classes.json).
Usage: python tools/gen_invocations.py"""
import json, re

ROOT = r"<workspace>\agentrpg-src"
c = [x for x in json.load(open(ROOT + r"\cmd\server\data\srd521_classes.json", encoding="utf-8")) if x["name"] == "Warlock"][0]


def text_of(blocks):
    out = []
    for b in blocks:
        if isinstance(b, str):
            out.append(b)
        elif isinstance(b, dict):
            if "trait" in b:
                out.append(f'{b["trait"]}. {b["text"]}')
            elif "bullet" in b:
                out.append("- " + b["bullet"])
    return "\n".join(out)


rows = []
on = False
for s in c["sections"]:
    if "Invocation Options" in s["heading"]:
        on = True
        continue
    if on and s["level"] >= 3 and not s["heading"].startswith("Level"):
        txt = text_of(s["blocks"])
        m = re.match(r"Prerequisite: Level (\d+)\+ Warlock", txt)
        level = int(m.group(1)) if m else 0
        slug = re.sub(r"[^a-z]+", "-", s["heading"].lower().replace("\u2019", "")).strip("-")
        pm = re.search(r"Pact of the (Blade|Chain|Tome) Invocation", txt.split(chr(10))[0])
        rows.append((slug, s["heading"], level, txt, pm.group(1).lower() if pm else ""))

out = ["package game", "", "// Code generated by tools/gen_invocations.py from the SRD 5.2.1 Eldritch Invocation Options; DO NOT EDIT.", "",
       "func init() {", "\told := AvailableInvocations", "\tAvailableInvocations = map[string]EldritchInvocation{}"]
for slug, name, level, txt, pact in rows:
    d = json.dumps(txt, ensure_ascii=False)
    out.append(f'\tAvailableInvocations["{slug}"] = invocation2024(old, "{slug}", {json.dumps(name, ensure_ascii=False)}, {level}, "{pact}", {d})')
out.append("}")
out.append("")
out.append("""// invocation2024 keeps the mechanics key of an invocation that already had one and gives it the SRD wording.
func invocation2024(old map[string]EldritchInvocation, slug, name string, level int, pact, text string) EldritchInvocation {
	inv := EldritchInvocation{Slug: slug, Name: name, Description: text, Prerequisites: InvocationPrerequisites{Level: level, Pact: pact}}
	if o, ok := old[slug]; ok {
		inv.Mechanics = o.Mechanics
	} else {
		inv.Mechanics = map[string]string{slug: "true"}
	}
	return inv
}""")
open(ROOT + r"\game\invocations_2024.go", "w", encoding="utf-8", newline="\n").write("\n".join(out) + "\n")
print(len(rows), "invocations")
