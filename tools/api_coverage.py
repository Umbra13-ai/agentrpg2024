"""Lists every API route the server registers and says whether docs/skill.md and the API reference (docs/swagger) mention it.

Run:  python tools/api_coverage.py            (prints a summary and writes API-COVERAGE.md)
"""
import json
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
import glob
main = chr(10).join(open(f, encoding="utf-8", errors="replace").read() for f in sorted(glob.glob(os.path.join(ROOT, "cmd", "server", "*.go"))))
skill = open(os.path.join(ROOT, "docs", "skill.md"), encoding="utf-8").read()
other_docs = ""
for f in ("README.md", "PLAYER_EXPERIENCE.md", "PLAYER_HEARTBEAT.md", "GAME_MASTER_EXPERIENCE.md", "GM_HEARTBEAT.md", "CAMPAIGN_DOCUMENT.md"):
    other_docs += open(os.path.join(ROOT, "docs", f), encoding="utf-8").read()
spec = json.load(open(os.path.join(ROOT, "docs", "swagger", "swagger.json"), encoding="utf-8"))
swagger_paths = " ".join(spec["paths"].keys())

routes = sorted(set(re.findall(r'http\.HandleFunc\("(/api/[^"]*)"', main)))


def norm(p):
    return p.rstrip("/")


# sub-routes handled inside the {id} handlers: case "name": under switch parts[1]; some cases sit inside a nested switch
# (combat/..., exploration/..., campaign/...), so they are listed under their real path
NESTED = {
    ("handleCampaignByID", "add"): ["combat/add"],
    ("handleCampaignByID", "next"): ["combat/next"],
    ("handleCampaignByID", "remove"): ["combat/remove"],
    ("handleCampaignByID", "skip"): ["combat/skip", "exploration/skip"],
    ("handleCampaignByID", "sections"): ["campaign/sections"],
    ("handleCampaignByID", "npcs"): ["campaign/npcs"],
    ("handleCampaignByID", "quests"): ["campaign/quests"],
}
subs = {}
for base, fn in (("/api/characters/{id}/", "handleCharacterByID"), ("/api/campaigns/{id}/", "handleCampaignByID"), ("/api/gm/", None)):
    if not fn:
        continue
    m = re.search(r"func %s\(" % fn, main)
    if not m:
        continue
    body = main[m.start(): m.start() + 60000]
    end = re.search(r"\n}\n", body)
    body = body[: end.start()] if end else body
    for c in re.findall(r'case "([a-z0-9\-]+)":', body):
        for path in NESTED.get((fn, c), [c]):
            subs[base + path] = fn

rows = []
for r in routes:
    rows.append((norm(r), "route"))
for s in sorted(subs):
    rows.append((s, "sub-route"))


def mentioned(path, text):
    p = path.replace("{id}", "")
    tail = p.rstrip("/").split("/")[-1]
    full = p.rstrip("/")
    return full in text or ("/" + tail + " " in text) or ("/" + tail + "`" in text) or ("/" + tail + '"' in text) or ("/" + tail + "\n" in text)


undoc = []
lines = ["# API coverage", "", "Every route the server registers, and whether the player guide (`docs/skill.md`), the other guides and the API reference (`/docs`) mention it.",
         "Generated by `tools/api_coverage.py`; run it after adding an endpoint.", "",
         "| Route | In skill.md | In other guides | In API reference |", "|---|---|---|---|"]
for path, kind in rows:
    a = mentioned(path, skill)
    b = mentioned(path, other_docs)
    c = norm(path) in swagger_paths or norm(path).replace("/api/characters/{id}/", "/api/characters/") in swagger_paths
    lines.append("| `%s` | %s | %s | %s |" % (path, "yes" if a else "NO", "yes" if b else "-", "yes" if c else "NO"))
    if not a and not b:
        undoc.append(path)
open(os.path.join(ROOT, "API-COVERAGE.md"), "w", encoding="utf-8").write("\n".join(lines) + "\n")
print("routes:", len(rows), "| not in any guide:", len(undoc), "| in the API reference:", sum(1 for p, k in rows if norm(p) in swagger_paths))
print("\n".join(undoc))
