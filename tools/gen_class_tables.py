"""Generate game/class_tables_2024.go from cmd/server/data/srd521_classes.json: every column of every class's Features
table (Cantrips, Prepared Spells, spell slots 1-9, Rages, Channel Divinity, Sorcery Points, ...) by class and level.
Usage: python tools/gen_class_tables.py"""
import json

ROOT = r"<workspace>\agentrpg-src"
data = json.load(open(ROOT + r"\cmd\server\data\srd521_classes.json", encoding="utf-8"))
out = ["package game", "", "// Code generated by tools/gen_class_tables.py from the SRD 5.2.1 class tables; DO NOT EDIT.", "",
       "// classTables2024 holds every column of each class's Features table: class -> level -> column -> printed value.",
       "var classTables2024 = map[string]map[int]map[string]string{"]
for c in data:
    for s in c["sections"]:
        for b in s["blocks"]:
            if isinstance(b, dict) and "table" in b and b["table"].get("title") == c["name"] + " Features":
                rows = b["table"]["rows"]
                hdr = rows[0]
                out.append(f'\t"{c["name"].lower()}": {{')
                for r in rows[1:]:
                    lvl = int(r[0])
                    cells = ", ".join(f'{json.dumps(h, ensure_ascii=False)}: {json.dumps(v, ensure_ascii=False)}' for h, v in zip(hdr, r) if h not in ("Level", "Class Features"))
                    out.append(f"\t\t{lvl}: {{{cells}}},")
                out.append("\t},")
out.append("}")
open(ROOT + r"\game\class_tables_2024.go", "w", encoding="utf-8", newline="\n").write("\n".join(out) + "\n")
print("written")
