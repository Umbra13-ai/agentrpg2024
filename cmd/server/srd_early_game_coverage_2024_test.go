package main

import (
	"fmt"
	"os"
	"sort"
	"strings"
	"testing"
)

// The early-game playtest set (owner, Nov 22): the SRD 5.2.1 monsters of CR 0, 1/8, 1/4, 1/2 and 1. Until the owner says otherwise
// this is the only target. TestSRDEarlyGameCoverage writes, from srdSentenceCoverage, the wording-family table of these monsters
// only (ordered by count) and one row per entry (trait, action, Bonus Action, Reaction): applied by the server with the rules named,
// applied in part with the rest shown to the GM, or flagged to the GM. SRD_EARLY_OUT receives the Markdown.

var earlyGameCRs = map[string]bool{"0": true, "1/8": true, "1/4": true, "1/2": true, "1": true}

func earlyGameMonsters() []srdMonster2024 {
	var out []srdMonster2024
	for _, m := range srdMonsters2024() {
		if earlyGameCRs[m.CR] {
			out = append(out, m)
		}
	}
	return out
}

func TestSRDEarlyGameCoverage(t *testing.T) {
	ms := earlyGameMonsters()
	cr := map[string]string{}
	entries := 0
	for _, m := range ms {
		cr[m.Name] = m.CR
		entries += len(m.Traits) + len(m.Actions) + len(m.BonusActions) + len(m.Reactions)
		if len(m.Legendary) > 0 {
			t.Errorf("%s (CR %s) has Legendary Actions: outside the early-game set's assumptions", m.Name, m.CR)
		}
	}
	if len(ms) != 134 || entries != 312 {
		t.Errorf("early-game set: %d monsters, %d entries; the owner's count is 134 and 312", len(ms), entries)
	}
	type entryKey struct{ monster, kind, entry string }
	type entryRow struct {
		statuses map[string]int
		rules    map[string]bool
		gm       []string
		silent   []string
	}
	rows := map[entryKey]*entryRow{}
	type fam struct {
		monsters map[string]bool
		count    int
		status   map[string]int
		rules    map[string]bool
		example  string
	}
	fams := map[string]*fam{}
	totals := map[string]int{}
	for _, v := range srdSentenceCoverage() {
		if _, ok := cr[v.Monster]; !ok {
			continue
		}
		k := entryKey{v.Monster, v.Kind, v.Entry}
		r := rows[k]
		if r == nil {
			r = &entryRow{statuses: map[string]int{}, rules: map[string]bool{}}
			rows[k] = r
		}
		r.statuses[v.Status]++
		r.rules[v.Rule] = true
		switch v.Status {
		case "gm":
			r.gm = append(r.gm, v.Sentence)
		case "unhandled":
			r.silent = append(r.silent, v.Sentence)
		}
		f := fams[v.Family]
		if f == nil {
			f = &fam{monsters: map[string]bool{}, status: map[string]int{}, rules: map[string]bool{}, example: v.Monster + " / " + v.Entry + ": " + v.Sentence}
			fams[v.Family] = f
		}
		f.monsters[v.Monster] = true
		f.count++
		f.status[v.Status]++
		f.rules[v.Rule] = true
		totals[v.Status]++
	}
	cell := func(s string) string { return strings.ReplaceAll(strings.ReplaceAll(s, "|", "/"), "\n", " ") }
	join := func(m map[string]bool) string {
		var s []string
		for k := range m {
			s = append(s, k)
		}
		sort.Strings(s)
		return strings.Join(s, "; ")
	}
	var b strings.Builder
	b.WriteString("# SRD 5.2.1 early-game monsters (CR 0 to 1): coverage\n\nGenerated by `SRD_EARLY_OUT=$PWD/docs/SRD_EARLY_GAME_COVERAGE.md go test ./cmd/server -run TestSRDEarlyGameCoverage`" +
		" (srd_early_game_coverage_2024_test.go) from `srdSentenceCoverage`, a model of the server's routes (not a route test). " +
		"Monsters of CR 0, 1/8, 1/4, 1/2 and 1 only. The route test is `TestPostgresEarlyGameEveryEntry` (srd_early_game_routes_2024_test.go): " +
		"every action, Bonus Action and Reaction of these monsters through POST /api/gm/narrate at a character, what is stored read back, " +
		"and every trait in the GM's view of the fight.\n\n")
	statusCount := map[string]int{}
	keys := make([]entryKey, 0, len(rows))
	for k := range rows {
		keys = append(keys, k)
	}
	kindOrder := map[string]int{"trait": 0, "action": 1, "bonus": 2, "reaction": 3}
	sort.Slice(keys, func(i, j int) bool {
		a, c := keys[i], keys[j]
		if a.monster != c.monster {
			return a.monster < c.monster
		}
		if a.kind != c.kind {
			return kindOrder[a.kind] < kindOrder[c.kind]
		}
		return a.entry < c.entry
	})
	entryStatus := func(r *entryRow) string {
		switch {
		case r.statuses["unhandled"] > 0:
			return "UNHANDLED"
		case r.statuses["gm"] > 0 && r.statuses["applied"] > 0:
			return "applied, rest GM-flagged"
		case r.statuses["gm"] > 0:
			return "GM-flagged"
		}
		return "applied"
	}
	for _, k := range keys {
		statusCount[entryStatus(rows[k])]++
	}
	fmt.Fprintf(&b, "Monsters: %d. Entries: %d (applied %d; applied with the rest GM-flagged %d; GM-flagged %d; unhandled %d). "+
		"Sentences: applied %d, GM-flagged %d, unhandled %d.\n\n", len(ms), len(keys), statusCount["applied"], statusCount["applied, rest GM-flagged"],
		statusCount["GM-flagged"], statusCount["UNHANDLED"], totals["applied"], totals["gm"], totals["unhandled"])

	b.WriteString("## Wording families (highest count first)\n\n| # | family | stat blocks | sentences | applied | GM | unhandled | rules | example |\n|---|---|---|---|---|---|---|---|---|\n")
	fk := make([]string, 0, len(fams))
	for k := range fams {
		fk = append(fk, k)
	}
	sort.Slice(fk, func(i, j int) bool {
		a, c := fams[fk[i]], fams[fk[j]]
		if a.count != c.count {
			return a.count > c.count
		}
		return fk[i] < fk[j]
	})
	for i, k := range fk {
		f := fams[k]
		fmt.Fprintf(&b, "| %d | %s | %d | %d | %d | %d | %d | %s | %s |\n", i+1, cell(k), len(f.monsters), f.count, f.status["applied"], f.status["gm"], f.status["unhandled"], cell(join(f.rules)), cell(f.example))
	}

	b.WriteString("\n## Every entry\n\n| monster | CR | kind | entry | status | rules | shown to the GM |\n|---|---|---|---|---|---|---|\n")
	for _, k := range keys {
		r := rows[k]
		st := entryStatus(r)
		gm := strings.Join(r.gm, " ")
		if len(r.silent) > 0 {
			gm = "SILENT: " + strings.Join(r.silent, " ") + " " + gm
		}
		if len(gm) > 220 {
			gm = gm[:217] + "..."
		}
		fmt.Fprintf(&b, "| %s | %s | %s | %s | %s | %s | %s |\n", k.monster, cr[k.monster], k.kind, cell(k.entry), st, cell(join(r.rules)), cell(gm))
		if st == "UNHANDLED" {
			t.Errorf("%s / %s: silent sentence(s): %q", k.monster, k.entry, r.silent)
		}
	}
	if len(keys) != entries {
		t.Errorf("%d entries in the table, %d in the stat blocks", len(keys), entries)
	}
	t.Logf("early game: %d monsters, %d entries %v, sentences %v", len(ms), len(keys), statusCount, totals)
	if out := os.Getenv("SRD_EARLY_OUT"); out != "" {
		if err := os.WriteFile(out, []byte(b.String()), 0o644); err != nil {
			t.Fatal(err)
		}
	}
}
